import numpy as np
import pandas as pd
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

class AdaptiveWaveReinforcementSystem:
    def __init__(self, model_normal, model_extreme, threshold=1.5):
        self.model_normal = model_normal      # XGBoost
        self.model_extreme = model_extreme    # Pipeline(StandardScaler, Ridge)
        self.threshold = threshold

    def fit(self, X_train, y_train):
        print("Langkah 1: Training model XGBoost pada data keseluruhan...")
        self.model_normal.fit(X_train, y_train)

        print("Langkah 2: Training model Ridge Pipeline dengan Asymmetric Weighting (Reinforcement)...")
        # Beri bobot pinalti 5x lebih besar pada sampel gelombang tinggi (> 1.5m)
        sample_weights = np.where(y_train > self.threshold, 5.0, 1.0)

        # PERBAIKAN DI SINI: Gunakan 'ridge__sample_weight' untuk mengarahkan bobot ke step Ridge di dalam Pipeline
        self.model_extreme.fit(X_train, y_train, ridge__sample_weight=sample_weights)
        return self

    def predict_adaptive(self, X_test):
        pred_normal = self.model_normal.predict(X_test)
        pred_extreme = self.model_extreme.predict(X_test)

        final_preds = []
        for p_norm, p_ext in zip(pred_normal, pred_extreme):
            # Reinforcement Logic:
            # Jika sinyal mendekati/melebihi threshold, alihkan ke prediksi Ridge
            if p_norm > 1.2 or p_ext > 1.2:
                weight_ridge = 0.8
                blend = (weight_ridge * p_ext) + ((1 - weight_ridge) * p_norm)
                final_preds.append(blend)
            else:
                final_preds.append(p_norm)

        return np.array(final_preds)

# ==========================================
# EKSEKUSI ADAPTIVE SYSTEM
# ==========================================
xgb_base = models['Baseline XGBoost']
ridge_base = models['Baseline Ridge']

adaptive_sys = AdaptiveWaveReinforcementSystem(
    model_normal=xgb_base,
    model_extreme=ridge_base,
    threshold=1.5
)
adaptive_sys.fit(X_train, y_train)

# Prediksi & Evaluasi
y_pred_adaptive = adaptive_sys.predict_adaptive(X_test)

